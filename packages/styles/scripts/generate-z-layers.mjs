/**
 * Generates generated/z-layers.js and generated/z-layers.d.ts: the z-index
 * scale for JS consumers (e.g. a windowing engine) that need numbers. The
 * `--z-layer-*` custom properties in tokens/foundation/primitives.css are the
 * source of truth; keys are their camelCased names, ordered by value.
 *
 * Usage: node scripts/generate-z-layers.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = path.join(packageRoot, 'src/tokens/foundation/primitives.css')
const jsPath = path.join(packageRoot, 'generated/z-layers.js')
const dtsPath = path.join(packageRoot, 'generated/z-layers.d.ts')

const css = await readFile(sourcePath, 'utf8')
const layers = [...css.matchAll(/--z-layer-([a-z-]+):\s*(-?\d+);/g)]
  .map(([, name, value]) => [name.replace(/-([a-z])/g, (_, c) => c.toUpperCase()), Number(value)])
  .sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]))
if (layers.length === 0) throw new Error(`No --z-layer-* tokens found in ${sourcePath}`)

const header =
  '// Generated by packages/styles/scripts/generate-z-layers.mjs from\n' +
  '// src/tokens/foundation/primitives.css. Do not edit.\n'
const js = `${header}export const Z_LAYERS = Object.freeze({\n${layers.map(([k, v]) => `  ${k}: ${v},`).join('\n')}\n})\n`
const dts =
  `${header}export declare const Z_LAYERS: {\n${layers.map(([k, v]) => `  readonly ${k}: ${v}`).join('\n')}\n}\n\n` +
  'export type ZLayer = keyof typeof Z_LAYERS\n'

const outputs = [
  [jsPath, js],
  [dtsPath, dts],
]
if (process.argv.includes('--check')) {
  const stale = []
  for (const [file, content] of outputs) {
    const current = await readFile(file, 'utf8').catch(() => '')
    if (current !== content) stale.push(path.relative(packageRoot, file))
  }
  if (stale.length) {
    process.stderr.write(
      `Stale z-layer output: ${stale.join(', ')}\nRun pnpm --filter @atom63/styles generate:z-layers.\n`
    )
    process.exit(1)
  }
  process.stdout.write(`z-layer output is current (${layers.length} layers).\n`)
} else {
  for (const [file, content] of outputs) await writeFile(file, content)
  process.stdout.write(`Wrote ${layers.length} z-layers.\n`)
}
