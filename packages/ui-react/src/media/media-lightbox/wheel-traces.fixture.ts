/**
 * Real `wheel` events, captured from a trackpad.
 *
 * The gesture thresholds these exercise were originally tuned against
 * hand-written fixtures, and those fixtures could not have found the bug they
 * were meant to guard: a made-up swipe is a run of identical deltas, while a
 * real one ramps up noisily, peaks, and decays, and a real *pair* of them is
 * separated by a trough where the fingers leave the surface. The lock read
 * that trough-less shape as one unbroken gesture and swallowed every swipe
 * after the first.
 *
 * So these are recordings rather than inventions. Each entry is
 * `[timeFromFirstEventMs, deltaX, deltaY]`, and `expectedTurns` is the number
 * of deliberate swipes the recording contains, confirmed with the person who
 * made it rather than inferred from the numbers.
 *
 * Captured with `.superpowers/wheel-capture.html`; replayed against candidate
 * rules with `.superpowers/wheel-replay.mjs`.
 */
export interface WheelTrace {
  readonly expectedTurns: number
  readonly events: readonly (readonly [number, number, number])[]
}

