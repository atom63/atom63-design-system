/**
 * Compiles the Tailwind utility classes that @atom63/ui-react components use
 * (layout, media, toaster, appearance controls) into src/styles/utilities.css,
 * which styles.css imports. Consumers without Tailwind then get every class the
 * components render; consumers with Tailwind get harmless duplicates.
 *
 * `--check` fails when the checked-in file no longer matches the components.
 */
import { spawnSync } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const inputPath = path.join(packageRoot, 'scripts/utilities.input.css')
const outputPath = path.join(packageRoot, 'src/styles/utilities.css')
const tailwindBin = path.join(packageRoot, 'node_modules/.bin/tailwindcss')

const header = `/*
 * Generated by scripts/generate-utilities-css.mjs from the Tailwind classes in
 * the component sources, compiled against @atom63/styles/tailwind. Do not edit manually;
 * run \`pnpm --filter @atom63/ui-react generate:utilities\`.
 */
`

const directory = await mkdtemp(path.join(tmpdir(), 'atom63-ui-react-utilities-'))
try {
  const compiledPath = path.join(directory, 'utilities.css')
  const result = spawnSync(tailwindBin, ['--input', inputPath, '--output', compiledPath], {
    cwd: packageRoot,
    encoding: 'utf8',
  })
  if (result.status !== 0) {
    process.stderr.write(result.stderr)
    throw new Error('Tailwind failed to compile the ui-react utilities')
  }

  const content = header + (await readFile(compiledPath, 'utf8'))
  if (process.argv.includes('--check')) {
    const current = await readFile(outputPath, 'utf8').catch(() => '')
    if (current !== content) {
      process.stderr.write('src/styles/utilities.css is stale. Run: pnpm --filter @atom63/ui-react generate:utilities\n')
      process.exitCode = 1
    } else {
      process.stdout.write('ui-react utilities.css is current.\n')
    }
  } else {
    await writeFile(outputPath, content)
    process.stdout.write(`Generated src/styles/utilities.css (${content.length} bytes).\n`)
  }
} finally {
  await rm(directory, { recursive: true, force: true })
}
